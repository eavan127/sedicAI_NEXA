def test_uploads_analyze_the_whole_file_not_just_the_first_window(model, tmp_path):
    """The old UI did iq[:512] and silently dropped everything after 160 us."""
    n = 8192
    raw = np.empty(n * 2, dtype=np.float32)
    raw[0::2] = np.random.randn(n)
    raw[1::2] = np.random.randn(n)
    path = tmp_path / "capture.f32"
    raw.tofile(path)
    s = load_upload(str(path), model, hop=256)
    assert len(s.iq) == n
    assert s.result.n_windows == 1 + (n - 512) // 256



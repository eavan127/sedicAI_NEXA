def test_context_3_two_classes_produce_one_combined_event(model):
    """FHSS 0.90 + JAMMING 0.85 -> both detected -> ONE event."""
    from dataclasses import replace
    s = load_scenario(model, total_duration=0.005, hop=512, seed=0)
    probs = np.zeros((4, 8), dtype=np.float32)
    probs[:, CLASSES.index("FHSS")] = 0.90
    probs[:, CLASSES.index("JAMMING")] = 0.85
    forced = replace(s.result, probs=probs, starts=np.arange(4) * 512)
    events = detections(forced, s.thresholds)
    assert len(events) == 1
    assert set(events[0].classes) == {"FHSS", "JAMMING"}


def test_context_4_display_rules_never_mutate_the_raw_result(model):
    """THE key isolation test: the raw per-window probabilities the scorecard
    would use must be identical before and after the display layer runs."""
    s = load_scenario(model, total_duration=0.01, hop=256, seed=0)
    raw_before = s.result.probs.copy()
    s.events(smoothed=True)
    s.tiers(smoothed=True)
    s.judged_events(smoothed=True)
    np.testing.assert_array_equal(s.result.probs, raw_before)


def test_raw_mode_bypasses_the_display_rules(model):
    """Raw mode must show what the model actually did, so the gate and hold
    are off there.

    Asserted on the RULES rather than on event counts. Counts depend on the
    model's predictions, and an untrained model's are arbitrary -- the earlier
    version compared raw vs smoothed counts and failed about one run in three.
    What matters is that raw mode passes no gate and no hold.
    """
    s = load_scenario(model, total_duration=0.02, hop=256, seed=0)
    assert s._rules(smoothed=False) == {"noise_gate": None, "hold_us": 0.0}
    assert s._rules(smoothed=True) == {"noise_gate": s.noise_gate,
                                        "hold_us": s.hold_us}



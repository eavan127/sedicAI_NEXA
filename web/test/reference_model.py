"""Shared by the *_reference.py scripts: the 60-class model the page runs, and
the Python display layer pointed at its classes.

The page runs results/classifier/physics_best.pt (web/models/best_model.onnx
is its export). src/timeline.py and src/ui/session.py still name the 8
classes in their module globals; their logic is class-agnostic, so the
references point those globals at the 60 classes, the page's tiers
(web/model_meta.js, generated by web/build.py) and its decision line
(configs/default.yaml web_threshold). The JS checks then hold the page to the
same rules on the same classes.
"""
import json
import re
from pathlib import Path

import torch

import src.timeline as timeline
import src.ui.session as ui_session
from src.config import CFG, DATASET_CLASSES
from src.models.amc_cnn import AMC_CNN

ROOT = Path(__file__).resolve().parents[2]
CKPT = ROOT / "results" / "classifier" / "physics_best.pt"
CLASSES = list(DATASET_CLASSES)
LINE = float(CFG.get("web_threshold", 0.3))
THRESHOLDS = {c: LINE for c in CLASSES}


def load_model():
    ck = torch.load(CKPT, map_location="cpu", weights_only=False)
    meta = ck["meta"]
    model = AMC_CNN(num_classes=len(CLASSES), input_len=meta["input_len"],
                    stft_n_fft=meta["stft_n_fft"], **meta["model_flags"])
    model.load_state_dict(ck["state_dict"])
    return model.eval()


def use_page_classes():
    meta_js = (ROOT / "web" / "model_meta.js").read_text(encoding="utf-8")
    tier_of = json.loads(re.search(r"export const TIER_OF = (.+?);$", meta_js, re.M).group(1))
    # civilian_library() reads the 8-class data/processed labels: it keeps
    # the 8 names (the civilian classes exist in both lists).
    old_classes, old_library = ui_session.CLASSES, ui_session.civilian_library

    def civilian_library(*args, **kwargs):
        ui_session.CLASSES = old_classes
        try:
            return old_library(*args, **kwargs)
        finally:
            ui_session.CLASSES = CLASSES

    ui_session.civilian_library = civilian_library
    timeline.CLASSES = ui_session.CLASSES = CLASSES
    timeline.CLASS_TO_IDX = {c: i for i, c in enumerate(CLASSES)}
    timeline._TIER_OF = tier_of
    ui_session.resolve_multilabel_thresholds = lambda: [LINE] * len(CLASSES)

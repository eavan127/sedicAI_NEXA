"""
Does a longer window help the classes one 160 us window cannot settle?
(SED-39, 2026-11-09: the "specialist" idea.)

The 60-class model sees 512 samples (160 us) per decision, fixed by RadChar.
QAM / APSK / PSK / ASK sizes and LTE/NR are the weakest classes, and the likely
reason is too few symbols per window. This trains the SAME small model at
several window lengths on ONLY those classes, generated by our own generators
(no RadChar, so no padding problem), and reports exact-class accuracy per
length. If accuracy climbs clearly with length, a second-stage specialist that
reads a longer stretch of a track is worth building; if it stays flat, it isn't.

Conditions, the same at every length:
  * classes: QAM (5), APSK (4), PSK (6), ASK (3), multicarrier (3) = 21
  * impairments: the full chain except placement; instead a small residual
    offset of up to +/-RESIDUAL_HZ, which is what extract.cut leaves after
    centring a box (so the model cannot use "exactly at 0 Hz" as a cue)
  * SNR bins SNRS, the same number of windows per (class, SNR) at every length
  * model: AMC_CNN, n_fft 64, keep_rows, whole-window spectrum branch, softmax
  * the same seeds, epochs and optimiser

Colab-safe: every length writes <out>/len_<L>.json when it finishes, and a rerun
skips lengths already done, so a disconnect only loses the length in progress.

    python scripts/window_length_check.py --out results/window_length            # all lengths
    python scripts/window_length_check.py --lengths 512 1024 --per-bin 50 --epochs 1 --out /tmp/wl   # quick check
"""
import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data import impairments  # noqa: E402
from src.data.merge import normalize_batch  # noqa: E402
from src.generators import analog, apsk, digital, multicarrier  # noqa: E402
from src.models.amc_cnn import AMC_CNN  # noqa: E402

GROUPS = {
    "QAM": (digital, ["16QAM", "32QAM", "64QAM", "128QAM", "256QAM"]),
    "APSK": (apsk, ["16APSK", "32APSK", "64APSK", "128APSK"]),
    "PSK": (digital, ["BPSK", "QPSK", "OQPSK", "8PSK", "16PSK", "32PSK"]),
    "ASK": (analog, ["OOK", "4ASK", "8ASK"]),
    "MULTICARRIER": (multicarrier, ["OFDM", "LTE_LIKE", "NR_LIKE"]),
}
CLASSES = [c for _, cs in GROUPS.values() for c in cs]
GROUP_OF = {c: g for g, (_, cs) in GROUPS.items() for c in cs}
GEN_OF = {c: m for m, cs in GROUPS.values() for c in cs}
SNRS = (-10, -6, -2, 2, 6, 10, 14, 18)
RESIDUAL_HZ = 20e3
SPLIT_SEED = {"train": 11, "val": 12, "test": 13}
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def make_window(cls, snr, L, rng):
    gen = GEN_OF[cls]
    gen.WINDOW_LEN = L                                    # every generator reads it at call time
    clean, params = gen.generate_window(cls, None, rng)
    bw = params.get("bandwidth_hz")
    if bw is None and np.isfinite(params.get("sps", np.nan)):
        beta = params.get("beta", 1.0)
        bw = impairments.FS / params["sps"] * (1 + (beta if np.isfinite(beta) else 1.0))
    x, _ = impairments.apply(clean, snr, rng, bandwidth_hz=bw, skip=("placement",))
    return impairments.frequency_shift(x, rng.uniform(-RESIDUAL_HZ, RESIDUAL_HZ))


def _bin(job):
    """One (class, SNR) bin: float16 (per_bin, 2, L). Seeded by (split, class, SNR, L)."""
    split, ci, s, L, per_bin = job
    rng = np.random.default_rng([SPLIT_SEED[split], ci, s + 100, L])
    W = np.stack([make_window(CLASSES[ci], float(s), L, rng) for _ in range(per_bin)])
    return normalize_batch(W).astype(np.float16)


def make_split(split, L, per_bin, workers=1):
    """float16 (N, 2, L) normalised windows, int64 labels, float SNRs. Deterministic
    per (split, L): the same classes and SNRs at every length, whatever `workers`."""
    jobs = [(split, ci, s, L, per_bin) for ci in range(len(CLASSES)) for s in SNRS]
    if workers > 1:
        from concurrent.futures import ProcessPoolExecutor
        with ProcessPoolExecutor(workers) as ex:
            parts = list(ex.map(_bin, jobs, chunksize=4))
    else:
        parts = [_bin(j) for j in jobs]
    X = np.concatenate(parts)
    y = np.repeat([ci for _, ci, _, _, _ in jobs], per_bin).astype(np.int64)
    snr = np.repeat([s for _, _, s, _, _ in jobs], per_bin).astype(np.float32)
    return X, y, snr


def evaluate(model, X, y, batch=256):
    model.eval()
    pred = []
    with torch.no_grad():
        for s in range(0, len(X), batch):
            pred.append(model(torch.from_numpy(X[s:s + batch].astype(np.float32)).to(DEVICE)).argmax(1).cpu().numpy())
    return np.concatenate(pred)


def scores(pred, y, snr):
    hit = pred == y
    grp_true = np.array([GROUP_OF[CLASSES[i]] for i in y])
    grp_pred = np.array([GROUP_OF[CLASSES[i]] for i in pred])
    out = {"top1": float(hit.mean()), "top1_high": float(hit[snr >= 10].mean()),
           "right_group": float((grp_true == grp_pred).mean()),
           "per_snr": {int(s): float(hit[snr == s].mean()) for s in SNRS},
           "group": {}, "group_high": {}, "per_class_high": {}}
    for g in GROUPS:
        m = grp_true == g
        out["group"][g] = float(hit[m].mean())
        out["group_high"][g] = float(hit[m & (snr >= 10)].mean())
    for i, c in enumerate(CLASSES):
        m = (y == i) & (snr >= 10)
        out["per_class_high"][c] = float(hit[m].mean())
    return out


def run_length(L, args):
    t0 = time.time()
    data = {sp: make_split(sp, L, n, args.workers) for sp, n in
            (("train", args.per_bin), ("val", max(1, args.per_bin // 6)), ("test", max(1, args.per_bin // 3)))}
    gen_s = time.time() - t0
    print(f"  L={L}: data made in {gen_s:.0f}s ({len(data['train'][0])} train windows)", flush=True)
    torch.manual_seed(0)
    model = AMC_CNN(num_classes=len(CLASSES), input_len=L, stft_n_fft=64, stft_freq_summary=False,
                    stft_keep_rows=True, cumulant_features=False, expert_features=False,
                    full_spectrum=True).to(DEVICE)
    opt = torch.optim.Adam(model.parameters(), lr=1e-3)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs)
    lossf = nn.CrossEntropyLoss()
    Xtr, ytr, _ = data["train"]
    best, best_state, history = -1.0, None, []
    for ep in range(args.epochs):
        model.train()
        perm = np.random.default_rng(ep).permutation(len(Xtr))
        tl = 0.0
        for s in range(0, len(perm), args.batch):
            idx = np.sort(perm[s:s + args.batch])
            xb = torch.from_numpy(Xtr[idx].astype(np.float32)).to(DEVICE)
            yb = torch.from_numpy(ytr[idx]).to(DEVICE)
            opt.zero_grad()
            loss = lossf(model(xb), yb)
            loss.backward()
            opt.step()
            tl += loss.item() * len(idx)
        sched.step()
        va = float((evaluate(model, data["val"][0], data["val"][1]) == data["val"][1]).mean())
        history.append({"epoch": ep + 1, "train_loss": tl / len(perm), "val_top1": va})
        if va > best:
            best, best_state = va, {k: v.detach().clone() for k, v in model.state_dict().items()}
        print(f"    epoch {ep + 1}/{args.epochs} loss {tl / len(perm):.3f} val {va:.3f} "
              f"({time.time() - t0:.0f}s)", flush=True)
    model.load_state_dict(best_state)
    Xte, yte, ste = data["test"]
    res = {"window_len": L, "window_us": L / 3.2, "per_bin": args.per_bin, "epochs": args.epochs,
           "seconds": round(time.time() - t0), "data_seconds": round(gen_s), "history": history,
           "test": scores(evaluate(model, Xte, yte), yte, ste)}
    return res


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--lengths", type=int, nargs="+", default=[512, 1024, 2048, 4096])
    p.add_argument("--per-bin", type=int, default=400, help="train windows per (class, SNR); val 1/6, test 1/3")
    p.add_argument("--epochs", type=int, default=10)
    p.add_argument("--batch", type=int, default=128)
    p.add_argument("--workers", type=int, default=1, help="processes for making the data (Colab: 2)")
    p.add_argument("--out", required=True)
    args = p.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    print(f"device {DEVICE}; {len(CLASSES)} classes x {len(SNRS)} SNRs; lengths {args.lengths}", flush=True)
    for L in args.lengths:
        f = out / f"len_{L}.json"
        if f.exists():
            print(f"  L={L}: already done, skipping ({f})")
            continue
        res = run_length(L, args)
        f.write_text(json.dumps(res, indent=1))
        t = res["test"]
        print(f"  L={L}: top-1 {t['top1']:.3f}, >=10 dB {t['top1_high']:.3f}, "
              + ", ".join(f"{g} {v:.2f}" for g, v in t["group_high"].items()), flush=True)

    done = [json.loads((out / f"len_{L}.json").read_text()) for L in args.lengths if (out / f"len_{L}.json").exists()]
    lines = [f"{'window':>12}{'top-1':>8}{'>=10dB':>8}" + "".join(f"{g[:5]:>8}" for g in GROUPS) + "   (>=10 dB per group)"]
    for r in done:
        t = r["test"]
        lines.append(f"{r['window_len']:>6} {r['window_us']:>4.0f}us{t['top1']:8.3f}{t['top1_high']:8.3f}"
                     + "".join(f"{t['group_high'][g]:8.3f}" for g in GROUPS))
    (out / "summary.txt").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
